import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.ensemble import RandomForestRegressor
from causalml.inference.meta import BaseTRegressor

# 1. simulate data (continuous outcome: spend)
np.random.seed(42)
n = 5000
age = np.random.randint(22, 65, size=n)
is_smb = np.random.binomial(1, 0.6, size=n)
engagement = np.random.gamma(shape=2.0, scale=2.0, size=n)

X = pd.DataFrame({
    "age": age,
    "is_smb": is_smb,
    "engagement": engagement
})

# randomized experiment
T = np.random.binomial(1, 0.5, size=n)

# baseline potential outcome
baseline_spend = 20 + 3*engagement + 5*(1 - is_smb) + np.random.normal(0, 5, size=n)

# true heterogeneous treatment effect (for simulation eval)
true_tau = 10*is_smb - 1.0*engagement   # SMB ↑, highly engaged ↓

# observed outcome
Y = baseline_spend + T * true_tau

# 2. fit T-learner (continuous uplift)
base_learner = RandomForestRegressor(
    n_estimators=200,
    max_depth=6,
    random_state=42
)
t_learner = BaseTRegressor(learner=base_learner)
t_learner.fit(X=X.values, treatment=T, y=Y)

ite_pred = t_learner.predict(X.values)

# 3. assemble df
df = X.copy()
df["treatment"] = T
df["spend"] = Y
df["ite_pred"] = ite_pred
df["true_tau"] = true_tau

# ----------------------------------------------------------
# EVALUATION PART
# ----------------------------------------------------------

# a) POLICY VALUE / CUMULATIVE INCREMENTAL GAIN
p_treat = 0.5  # randomized 50/50
df["ipw_value"] = df["spend"] * (df["treatment"]/p_treat - (1 - df["treatment"])/(1 - p_treat))

df_sorted = df.sort_values("ite_pred", ascending=False).reset_index(drop=True)
df_sorted["cum_value"] = df_sorted["ipw_value"].cumsum()

plt.figure()
plt.plot(np.arange(1, len(df_sorted)+1)/len(df_sorted), df_sorted["cum_value"])
plt.title("Cumulative Incremental Gain (Policy Value Curve)")
plt.xlabel("Fraction of population targeted")
plt.ylabel("Cumulative incremental value")
plt.show()

# b) DECILE ATE CURVE
df["uplift_bin"] = pd.qcut(df["ite_pred"], 10, labels=False)

def decile_ate(gr):
    treated = gr[gr["treatment"] == 1]["spend"]
    control = gr[gr["treatment"] == 0]["spend"]
    return treated.mean() - control.mean()

ate_by_bin = df.groupby("uplift_bin").apply(decile_ate)

plt.figure()
plt.bar(ate_by_bin.index.astype(str), ate_by_bin.values)
plt.title("Observed ATE by Predicted-Uplift Decile")
plt.xlabel("Predicted uplift decile (0=lowest, 9=highest)")
plt.ylabel("Observed ATE (spend)")
plt.show()

# c) CALIBRATION (PRED vs OBSERVED)
df["pred_bin"] = pd.qcut(df["ite_pred"], 10)
observed = df.groupby("pred_bin").apply(decile_ate)
predicted = df.groupby("pred_bin")["ite_pred"].mean()

plt.figure()
plt.plot(predicted.values, observed.values, marker="o")
plt.title("Treatment-Effect Calibration")
plt.xlabel("Predicted uplift (avg in bin)")
plt.ylabel("Observed uplift (avg in bin)")
plt.axhline(0, linewidth=1)
plt.show()

# d) ATE sanity check
ate_emp = df[df["treatment"]==1]["spend"].mean() - df[df["treatment"]==0]["spend"].mean()
ate_pred = df["ite_pred"].mean()
print("Empirical ATE:", ate_emp)
print("Predicted ATE:", ate_pred)

# e) (since this is simulated) true ITE accuracy
from sklearn.metrics import mean_squared_error, r2_score
mse = mean_squared_error(df["true_tau"], df["ite_pred"])
r2 = r2_score(df["true_tau"], df["ite_pred"])
print("ITE MSE (vs true):", mse)
print("ITE R^2 (vs true):", r2)

